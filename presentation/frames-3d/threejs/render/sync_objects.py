"""Sync the 3D hero objects (presentation/frames-3d/objects/<name>/) into the film.

For each object: hero.png -> film/assets/objects/<name>/hero.png (800 px), and when the
sequences exist, spin/0000-0071.png and tumble/0000-0047.png -> one sprite atlas each
(spin.png / tumble.png, CELL px per frame, 8 columns). Writes film/assets/objects/manifest.js
(window.DAYBREAK_OBJECTS) that the 2D layer reads; objects without sequences fall back
to the hero with 2D rotation. Re-run whenever the objects team delivers more.

    python3 render/sync_objects.py
"""
from __future__ import annotations

import json
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
SRC = HERE.parents[1] / "objects"
DST = HERE.parent / "film" / "assets" / "objects"
NAMES = ["truck", "meter", "pole", "solar", "hardhat", "pin_orange", "pin_cyan", "pin_blue", "cloud"]
CELL = 384
COLS = 8


def atlas(frames: list[Path], out: Path) -> dict:
    rows = (len(frames) + COLS - 1) // COLS
    sheet = Image.new("RGBA", (COLS * CELL, rows * CELL), (0, 0, 0, 0))
    for i, f in enumerate(frames):
        im = Image.open(f).convert("RGBA").resize((CELL, CELL), Image.LANCZOS)
        sheet.paste(im, ((i % COLS) * CELL, (i // COLS) * CELL))
    sheet.save(out, optimize=True)
    return {"frames": len(frames), "cols": COLS, "cell": CELL, "rows": rows}


def main() -> None:
    DST.mkdir(parents=True, exist_ok=True)
    manifest = {}
    for n in NAMES:
        src = SRC / n
        if not (src / "hero.png").exists():
            continue
        d = DST / n
        d.mkdir(exist_ok=True)
        Image.open(src / "hero.png").convert("RGBA").resize((800, 800), Image.LANCZOS).save(d / "hero.png", optimize=True)
        entry = {"hero": f"assets/objects/{n}/hero.png"}
        for mode in ("spin", "tumble"):
            frames = sorted((src / mode).glob("*.png")) if (src / mode).exists() else []
            if len(frames) >= 8:
                info = atlas(frames, d / f"{mode}.png")
                entry[mode] = {"src": f"assets/objects/{n}/{mode}.png", **info}
        src_manifest = src / "manifest.json"
        if src_manifest.exists():
            entry["source"] = json.loads(src_manifest.read_text())
        manifest[n] = entry
        print(n, "hero" + (" +spin" if "spin" in entry else "") + (" +tumble" if "tumble" in entry else ""))
    (DST / "manifest.js").write_text("// generated by render/sync_objects.py\nwindow.DAYBREAK_OBJECTS = "
                                     + json.dumps(manifest, indent=1) + ";\n")


if __name__ == "__main__":
    main()
