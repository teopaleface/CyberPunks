"""Sync the v3 premium plates (presentation/frames-3d/plates_v3/) into film_v3.

For each plate name: up/<name>.png -> film_v3/assets/plates/<name>.jpg (2880x1620) and
cut/<name>.png -> <name>_cut.png (alpha cutout, 2880x1620). When a plate is not delivered
yet, a placeholder with the same name and layout is made from the v7 concept images
(frames-codex/v7/concepts + styleframes/assets cutouts). Re-run when plates arrive; the film
picks them up with no code change. Writes assets/plates/manifest.js (window.V3_PLATES).

    python3 render/v3_plates.py
"""
from __future__ import annotations

import json
from pathlib import Path

from PIL import Image, ImageEnhance

HERE = Path(__file__).resolve().parent
F3D = HERE.parents[0].parent  # presentation/frames-3d
SRC = F3D / "plates_v3"
CONC = F3D.parent / "frames-codex" / "v7" / "concepts"
CUTS = F3D / "styleframes" / "assets"
DST = HERE.parent / "film_v3" / "assets" / "plates"
W, H = 2880, 1620
NAVY = (0, 15, 30)
NAMES = ["p01_storm", "p02_dark", "p03_meter", "p03_solar", "p04_wide", "p06_unfold", "p07_map", "p10_house", "p11_dawn", "p12_day"]

# placeholder recipe: (concept, cutout or None, crop box in concept px (x0,y0,x1,y1) or None, brightness)
PH = {
    "p01_storm": ("planet_storm", "planet_storm_cut", None, 1.0),
    "p02_dark": ("planet_storm", "planet_storm_cut", None, 0.55),
    "p03_meter": ("planet_storm", None, (1080, 330, 1480, 555), 1.0),
    "p03_solar": ("planet_routes", None, (1180, 380, 1560, 594), 1.12),
    "p04_wide": ("planet_routes", "planet_routes_cut", None, 1.0),
    "p06_unfold": ("popup_map", None, None, 1.0),
    "p07_map": ("popup_map", None, (0, 470, 760, 897), 1.0),
    "p10_house": ("planet_routes", None, (1180, 230, 1540, 433), 1.0),
    "p11_dawn": ("planet_dawn", "planet_dawn_cut", None, 1.0),
    "p12_day": ("planet_dawn", "planet_dawn_cut", None, 1.18),
}


def fit(im: Image.Image, box=None) -> Image.Image:
    if box:
        im = im.crop(box)
    return im.resize((W, H), Image.LANCZOS)


def main() -> None:
    DST.mkdir(parents=True, exist_ok=True)
    man = {}
    for n in NAMES:
        up_src, cut_src = SRC / "up" / f"{n}.png", SRC / "cut" / f"{n}.png"
        entry = {"up": f"assets/plates/{n}.jpg"}
        if up_src.exists():
            fit(Image.open(up_src).convert("RGB")).save(DST / f"{n}.jpg", quality=92)
            entry["placeholder"] = False
            if cut_src.exists():
                try:
                    fit(Image.open(cut_src).convert("RGBA")).save(DST / f"{n}_cut.png", optimize=True)
                    entry["cut"] = f"assets/plates/{n}_cut.png"
                except OSError as e:  # still being written by the plates team
                    print(n, "cut not ready:", e)
        elif sorted((SRC / "attempts").glob(f"{n}_a*.png")):
            # newest attempt from the plates team: a much closer stand-in than the concept image
            att = sorted((SRC / "attempts").glob(f"{n}_a*.png"))[-1]
            fit(Image.open(att).convert("RGB")).save(DST / f"{n}.jpg", quality=90)
            entry["placeholder"] = "attempt " + att.name
        else:
            conc, cut, box, bri = PH[n]
            im = fit(Image.open(CONC / f"{conc}.png").convert("RGB"), box)
            if bri != 1.0:
                im = ImageEnhance.Brightness(im).enhance(bri)
            im.save(DST / f"{n}.jpg", quality=90)
            entry["placeholder"] = True
            if cut:
                c = fit(Image.open(CUTS / f"{cut}.png").convert("RGBA"), box)
                if bri != 1.0:
                    rgb = ImageEnhance.Brightness(c.convert("RGB")).enhance(bri)
                    rgb.putalpha(c.getchannel("A"))
                    c = rgb
                c.save(DST / f"{n}_cut.png", optimize=True)
                entry["cut"] = f"assets/plates/{n}_cut.png"
        man[n] = entry
        print(n, entry["placeholder"] if isinstance(entry["placeholder"], str) else ("PLACEHOLDER" if entry["placeholder"] else "plate"), "+cut" if "cut" in entry else "")
    (DST / "manifest.js").write_text("// generated by render/v3_plates.py\nwindow.V3_PLATES = " + json.dumps(man, indent=1) + ";\n")


if __name__ == "__main__":
    main()
