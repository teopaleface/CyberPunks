// Planet Daybreak: render the 3D layer and export camera/anchor tracks.
//
//   node render/film3d.mjs tracks                       -> camera_path.json + film/assets/tracks.js (900 frames)
//   node render/film3d.mjs frames --times 1.5,7.5 --spp 96 [--mblur]
//   node render/film3d.mjs frames --from 0 --to 899 --step 1 --spp 16 --mblur [--w 960 --h 540]
//   node render/film3d.mjs probe --t 1.5 --spp 32 --out /tmp/p.png
// Frames go to film/assets/frames3d/f0000.jpg (frame = round(t * 30)).
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILM = path.join(ROOT, 'film');
const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const args = process.argv.slice(2);
const mode = args[0] || 'probe';
const opt = (k, d) => { const i = args.indexOf('--' + k); return i >= 0 ? args[i + 1] : d; };
const flag = (k) => args.includes('--' + k);

const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.json': 'application/json' };
const server = http.createServer((req, res) => {
  const p = path.join(ROOT, decodeURIComponent(new URL(req.url, 'http://x').pathname));
  if (!p.startsWith(ROOT) || !fs.existsSync(p) || fs.statSync(p).isDirectory()) { res.writeHead(404); res.end(); return; }
  res.writeHead(200, { 'Content-Type': MIME[path.extname(p)] || 'application/octet-stream' });
  fs.createReadStream(p).pipe(res);
});
await new Promise((r) => server.listen(0, '127.0.0.1', r));
const W = +opt('w', 1920), H = +opt('h', 1080);
const browser = await chromium.launch({ executablePath: CHROME, headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist', '--disable-gpu-watchdog'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
page.on('console', (m) => { if (m.type() === 'error' || m.text().startsWith('[planet]')) console.log('  [page]', m.text()); });
page.on('pageerror', (e) => console.log('  [pageerror]', e.message));
const t0 = Date.now();
await page.goto(`http://127.0.0.1:${server.address().port}/planet.html?t=0&spp=1&w=${W}&h=${H}`);
await page.waitForFunction(() => window.__planetReady === true, null, { timeout: 300000 });
console.log(`scene built in ${((Date.now() - t0) / 1000).toFixed(1)} s`);

async function frame(t, spp, out, mblur) {
  const jpg = out.endsWith('.jpg');
  const r = await page.evaluate(({ t, spp, mblur, jpg }) => {
    const ms = window.planet.renderFrame(t, spp, { mblur });
    return { ms, data: window.planet.png(jpg ? 'image/jpeg' : 'image/png', 0.93) };
  }, { t, spp, mblur, jpg });
  fs.writeFileSync(out, Buffer.from(r.data.split(',')[1], 'base64'));
  return r.ms;
}

if (mode === 'tracks') {
  const frames = 900;
  const data = await page.evaluate((n) => { const a = []; for (let i = 0; i < n; i++) a.push(window.planet.tracks(i / 30)); return a; }, frames);
  const doc = {
    about: 'Planet Daybreak camera + anchor tracks, one entry per frame (30 fps, 1920x1080). World: planet centre at origin, +Y up, planet radius 1.0, village on the north pole (+Y). Camera: perspective, vertical fov in degrees, looking from position to target with world up +Y, plus a lens shift (fraction of the half frame, +x moves the image content left, +y moves it down) applied as an off-axis frustum. anchors.*.px = screen pixels (origin top-left). f = flat(0)/planet(1) blend.',
    fps: 30, width: 1920, height: 1080, planetRadius: 1.0, frames: data,
  };
  fs.writeFileSync(path.join(ROOT, 'camera_path.json'), JSON.stringify(doc));
  // compact tracks for the 2D layer
  const names = Object.keys(data[0].anchors);
  const compact = { fps: 30, names, f: data.map((d) => d.f), planetR: data.map((d) => d.anchors.planet.radiusPx) };
  for (const n of names) compact[n] = data.map((d) => [d.anchors[n].px[0], d.anchors[n].px[1], d.anchors[n].visible ? 1 : 0]);
  fs.mkdirSync(path.join(FILM, 'assets'), { recursive: true });
  compact.map = await page.evaluate(() => window.planet.mapLayout(10.1));
  doc.map = compact.map;
  fs.writeFileSync(path.join(ROOT, 'camera_path.json'), JSON.stringify(doc));
  fs.writeFileSync(path.join(FILM, 'assets', 'tracks.js'), `// generated by render/film3d.mjs tracks - do not edit\nwindow.DAYBREAK_TRACKS = ${JSON.stringify(compact)};\n`);
  console.log(`tracks: ${frames} frames, anchors: ${names.join(', ')}`);
} else if (mode === 'frames') {
  const spp = +opt('spp', 64);
  const mblur = flag('mblur');
  const dir = path.join(FILM, 'assets', 'frames3d');
  fs.mkdirSync(dir, { recursive: true });
  let list;
  if (opt('times')) list = opt('times').split(',').map((s) => Math.round(+s * 30));
  else { list = []; for (let i = +opt('from', 0); i <= +opt('to', 899); i += +opt('step', 1)) list.push(i); }
  let total = 0;
  for (const fr of list) {
    const ms = await frame(fr / 30, spp, path.join(dir, `f${String(fr).padStart(4, '0')}.jpg`), mblur);
    total += ms;
    if (list.length < 20 || fr % 30 === 0) console.log(`frame ${fr} (t=${(fr / 30).toFixed(2)}) ${(ms / 1000).toFixed(2)} s`);
  }
  const have = fs.readdirSync(dir).filter((f) => /^f\d{4}\.jpg$/.test(f)).map((f) => +f.slice(1, 5)).sort((x, y) => x - y);
  fs.writeFileSync(path.join(dir, 'manifest.js'), `// generated by render/film3d.mjs - available 3D frames\nwindow.DAYBREAK_FRAMES = ${JSON.stringify(have)};\n`);
  const rep = { spp, mblur, frames: list.length, seconds: +(total / 1000).toFixed(1), perFrame: +(total / list.length / 1000).toFixed(3), size: [W, H] };
  fs.writeFileSync(path.join(dir, '..', 'frames3d_timings.json'), JSON.stringify(rep, null, 2));
  console.log(rep);
} else if (mode === 'probe') {
  const ms = await frame(+opt('t', 1.5), +opt('spp', 16), opt('out', '/tmp/planet_probe.png'), flag('mblur'));
  console.log(`probe ${(ms / 1000).toFixed(2)} s`);
}
await browser.close();
server.close();
