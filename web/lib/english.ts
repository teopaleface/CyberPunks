const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const MONTHS: Record<string, string> = Object.fromEntries(
  ["ianuarie", "februarie", "martie", "aprilie", "mai", "iunie", "iulie", "august", "septembrie", "octombrie", "noiembrie", "decembrie"]
    .map((month, i) => [month, ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"][i]]),
);
const DAYS: Record<string, string> = { luni: "Monday", marți: "Tuesday", miercuri: "Wednesday", joi: "Thursday", vineri: "Friday", sâmbătă: "Saturday", duminică: "Sunday" };
const TOKENS: Record<string, string> = {
  n: "~?[+−-]?\\d+(?:[.,]\\d+)*",
  id: "[A-Za-z0-9_-]+",
  time: "\\d{1,2}:\\d{2}",
  iso: "\\d{4}-\\d{2}-\\d{2}",
  date: "\\d{1,2}\\.\\d{1,2}\\.\\d{4}",
  day: Object.keys(DAYS).join("|"),
  month: Object.keys(MONTHS).join("|"),
  text: ".+?",
  place: ".+?",
  area: "[^,;]+?",
};
const rules = [...TEMPLATES].sort((a, b) => b[0].replace(/\{\w+\}/g, "").length - a[0].replace(/\{\w+\}/g, "").length).map(([source, target]) => {
  const kinds: string[] = [];
  const re = source.split(/(\{\w+\})/).map((part) => {
    const kind = /^\{(\w+)\}$/.exec(part)?.[1];
    if (!kind) return escape(part);
    kinds.push(kind);
    return `(${TOKENS[kind]})`;
  }).join("");
  return { re: new RegExp(`^${re}$`, "iu"), target, kinds };
});

function numberText(raw: string, currency: boolean): string {
  const prefix = raw.startsWith("~") ? "~" : "";
  const digits = raw.replace(/^~/, "").replace("−", "-");
  const normal = digits.includes(",") ? digits.replaceAll(".", "").replace(",", ".") : currency && /^[-+]?\d{1,3}(?:\.\d{3})+$/.test(digits) ? digits.replaceAll(".", "") : digits;
  if (!currency) return prefix + normal;
  const decimals = normal.includes(".") ? normal.split(".")[1].length : 0;
  return prefix + new Intl.NumberFormat("en-GB", { minimumFractionDigits: decimals, maximumFractionDigits: Math.min(20, decimals) }).format(Number(normal));
}

function translate(text: string, depth: number): string {
  if (!text || depth > 40) return text;
  const exact = EXACT[text.toLocaleLowerCase("ro-RO")];
  if (exact) return /^[A-ZĂÂÎȘȚ]/.test(text) ? exact.charAt(0).toUpperCase() + exact.slice(1) : exact;
  const punctuation = /[.;,]$/.test(text) ? text.at(-1)! : "";
  const core = punctuation ? text.slice(0, -1) : text;
  const coreExact = EXACT[core.toLocaleLowerCase("ro-RO")];
  if (coreExact) return translate(core, depth + 1) + punctuation;
  // Translate complete sentences before a broad wrapper captures an entire paragraph.
  let sentenceDepth = 0;
  for (let i = 0; i < text.length - 1; i++) {
    if (text[i] === "(") sentenceDepth++;
    if (text[i] === ")") sentenceDepth--;
    if (sentenceDepth === 0 && text[i] === "." && text[i + 1] === " ") {
      return translate(text.slice(0, i + 1), depth + 1) + " " + translate(text.slice(i + 2), depth + 1);
    }
  }
  for (const rule of rules) {
    const match = rule.re.exec(core);
    if (!match) continue;
    return rule.target.replace(/\$(\d+)/g, (token, index: string, offset: number) => {
      const i = Number(index);
      const raw = match[i];
      const kind = rule.kinds[i - 1];
      if (kind === "n") return numberText(raw, /^ (?:RON|customers|solar customers)\b/.test(rule.target.slice(offset + token.length)));
      if (kind === "month") return MONTHS[raw.toLocaleLowerCase("ro-RO")];
      if (kind === "date") return raw.replaceAll(".", "/");
      if (kind === "day") return DAYS[raw.toLocaleLowerCase("ro-RO")];
      return kind === "text" || kind === "place" || kind === "area" ? translate(raw, depth + 1) : raw;
    }) + punctuation;
  }
  // Prefer complete sentences so semicolons inside a known template stay intact.
  for (const separator of [";", ","]) {
    let nesting = 0;
    for (let i = 0; i < text.length - 1; i++) {
      if (text[i] === "(") nesting++;
      if (text[i] === ")") nesting--;
      if (nesting === 0 && text[i] === separator && text[i + 1] === " ") {
        return translate(text.slice(0, i + 1), depth + 1) + " " + translate(text.slice(i + 2), depth + 1);
      }
    }
  }
  return text;
}

export function englishText(text: string): string {
  const core = text.trim();
  if (!core) return text;
  // IDs are opaque. Translate only copy explicitly passed at a display boundary.
  if (/^[A-Za-z0-9]+(?:[-_][A-Za-z0-9]+)+$/.test(core)) return text;
  return text.replace(core, translate(core, 0)).replace(/\(sintetic\)/giu, "(synthetic)").replace(/\(simulată\)/giu, "(simulated)");
}
